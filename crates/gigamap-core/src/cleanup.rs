//! Cleanup candidates: regenerable build output, caches and temp folders.
//! Each candidate carries a safety level; nothing is ever deleted here.

use crate::index::{flag, Index, NodeId};
use serde::Serialize;

#[derive(Serialize, Clone, Copy, Debug, PartialEq, Eq)]
pub enum Safety {
    /// Regenerated automatically (build output, package caches).
    Safe,
    /// Usually fine, but look first (downloads, old installers, VM disks).
    Review,
    /// Shown for information only; managed by Windows.
    System,
}

#[derive(Serialize, Clone, Debug)]
pub struct Candidate {
    pub id: NodeId,
    pub path: String,
    pub size: u64,
    pub kind: &'static str,
    pub why: &'static str,
    pub safety: Safety,
}

struct Rule {
    name: &'static str,
    kind: &'static str,
    why: &'static str,
    safety: Safety,
    /// Sibling that must exist (case-insensitive) for the match to count.
    sibling: Option<&'static [&'static str]>,
    /// Parent folder name that must match.
    parent: Option<&'static str>,
}

