const FILE_RULES: &[(&str, &str, &str, Safety)] = &[
    ("hiberfil.sys", "Hibernation file", "managed by Windows (powercfg /h off)", Safety::System),
    ("pagefile.sys", "Page file", "managed by Windows", Safety::System),
    ("swapfile.sys", "Swap file", "managed by Windows", Safety::System),
    ("ext4.vhdx", "WSL/Docker disk", "virtual disk, compact it instead of deleting", Safety::Review),
    ("docker_data.vhdx", "Docker disk", "virtual disk, prune Docker first", Safety::Review),
];

fn has_sibling(idx: &Index, parent: NodeId, wanted: &str) -> bool {
    let w = wanted.to_ascii_lowercase();
    idx.kids(parent).iter().any(|&k| {
        let n = idx.name(k).to_ascii_lowercase();
        match w.strip_prefix('*') {
            Some(suffix) => n.ends_with(suffix),
            None => n == w,
        }
    })
}

pub fn candidates(idx: &Index, scope: NodeId, min_size: u64) -> Vec<Candidate> {
    let mut out = Vec::new();
    let mut stack = vec![scope];
    while let Some(cur) = stack.pop() {
        let mut matched = false;
        if cur != 0 && idx.total_size[cur as usize] >= min_size {
            let name = idx.name(cur);
            let parent = idx.parent[cur as usize];
            if idx.is_dir(cur) {
                for r in RULES {
                    if !name.eq_ignore_ascii_case(r.name) {
                        continue;
                    }
                    if let Some(p) = r.parent {
                        if !idx.name(parent).eq_ignore_ascii_case(p) {
                            continue;
                        }
                    }
                    if let Some(sibs) = r.sibling {
                        if !sibs.iter().any(|s| has_sibling(idx, parent, s)) {
                            continue;
                        }
                    }
                    out.push(Candidate {
                        id: cur,
                        path: idx.path(cur),
                        size: idx.total_size[cur as usize],
                        kind: r.kind,
                        why: r.why,
                        safety: r.safety,
                    });
                    matched = true;
                    break;
                }
            } else {
                for (fname, kind, why, safety) in FILE_RULES {
                    if name.eq_ignore_ascii_case(fname) {
                        out.push(Candidate {
                            id: cur,
                            path: idx.path(cur),
                            size: idx.size[cur as usize],
                            kind,
                            why,
                            safety: *safety,
                        });
                    }
                }
            }
        }
        // Never descend into a matched candidate or NTFS metadata.
        if !matched && idx.flags[cur as usize] & flag::META == 0 {
            for &k in idx.kids(cur) {
                if idx.total_size[k as usize] >= min_size {
                    stack.push(k);
                }
            }
        }
    }
    out.sort_unstable_by(|a, b| b.size.cmp(&a.size));
    out
}

#[cfg(test)]
mod tests {
    use crate::index::{flag, IndexBuilder, ScanMethod};

    #[test]
    fn unity_library_needs_project_markers() {
        let mut b = IndexBuilder::new("D:\\", '\\', ScanMethod::Walk);
        let proj = b.push(0, "MyGame", 0, 0, 0, flag::DIR);
        b.push(proj, "Assets", 0, 0, 0, flag::DIR);
        b.push(proj, "ProjectSettings", 0, 0, 0, flag::DIR);
        let lib = b.push(proj, "Library", 0, 0, 0, flag::DIR);
        b.push(lib, "artifacts", 9 << 30, 0, 0, 0);
        let other = b.push(0, "Library", 0, 0, 0, flag::DIR);
        b.push(other, "book.pdf", 5 << 30, 0, 0, 0);
        let i = b.finish(std::time::Instant::now());
        let c = super::candidates(&i, 0, 1 << 20);
        assert_eq!(c.len(), 1);
        assert_eq!(c[0].path, "D:\\MyGame\\Library");
    }
}
